package io.legado.app.ui.config

import io.legado.app.help.ai.AiModelGenerationTestProtocol
import io.legado.app.help.ai.AiProviderSetting
import io.legado.app.help.ai.AiProviderType
import io.legado.app.help.ai.aiProviderHost
import io.legado.app.help.ai.apiKeyNeedsReentry
import io.legado.app.help.ai.generationApiPath
import io.legado.app.help.ai.modelGenerationTestProtocol
import io.legado.app.help.ai.modelGenerationTestProtocols
import io.legado.app.help.ai.normalizeAiApiPath
import okhttp3.HttpUrl.Companion.toHttpUrlOrNull

internal fun AiProviderSetting.toProviderFormScreenState(
    providerTypeLabel: String
): AiProviderFormScreenState {
    return AiProviderFormScreenState(
        providerId = id,
        builtIn = builtIn,
        providerType = providerTypeLabel,
        name = name,
        nameAutoGenerated = !builtIn && name.isNotBlank() && name == aiProviderHost(baseUrl),
        apiKey = apiKey,
        apiKeyNeedsReentry = apiKeyNeedsReentry(),
        baseUrl = baseUrl,
        chatPath = chatCompletionsPath,
        timeoutSeconds = timeoutSeconds.toString(),
        enabled = enabled,
        streamResponseEnabled = streamResponseEnabled,
        openAiCompatible = type == AiProviderType.OPENAI,
        useCustomBalanceUrl = useCustomBalanceUrl,
        balanceUrl = normalizeAiApiPath(baseUrl, balanceUrl),
        balanceJsonPath = balanceJsonPath,
        useCustomModelsUrl = useCustomModelsUrl,
        modelsUrl = normalizeAiApiPath(baseUrl, modelsUrl)
    ).withProtocolFields(this)
}

internal fun AiProviderFormScreenState.withProtocolFields(
    provider: AiProviderSetting,
    keepPathDraft: Boolean = false,
): AiProviderFormScreenState {
    val protocol = provider.modelGenerationTestProtocol()
    val responsesActive = protocol == AiModelGenerationTestProtocol.RESPONSES
    val keepDraft = keepPathDraft && responsesActive == responsesApiActive
    val path = provider.generationApiPath(protocol).orEmpty()
    val displayPath = if (provider.builtIn) path.toHttpUrlOrNull()?.encodedPath ?: path else path
    return copy(
        responsesPath = if (keepDraft && responsesActive) responsesPath else provider.responsesApiPath,
        useResponsesApi = provider.useResponsesApi,
        responsesApiAvailable = AiModelGenerationTestProtocol.RESPONSES in
            provider.modelGenerationTestProtocols(),
        responsesApiActive = responsesActive,
        apiPathValue = if (keepDraft) apiPathValue else displayPath,
    )
}

internal fun AiProviderFormScreenState.applyTo(
    source: AiProviderSetting
): AiProviderSetting {
    val resolvedBaseUrl = baseUrl.trim().ifBlank { source.baseUrl }
    val pathEditable = !source.builtIn && source.type == AiProviderType.OPENAI
    val savedChatPath = if (pathEditable) {
        chatPath.trim().ifBlank { source.chatCompletionsPath }
    } else {
        source.chatCompletionsPath
    }
    val previousResponsesPath = source.responsesApiPath
        ?: source.generationApiPath(AiModelGenerationTestProtocol.RESPONSES)
            ?.takeIf {
                savedChatPath != source.chatCompletionsPath && it == source.chatCompletionsPath.trim()
            }
    val savedResponsesPath = if (pathEditable && responsesPath != null) {
        normalizeAiApiPath(resolvedBaseUrl, responsesPath).ifBlank { null }
    } else {
        previousResponsesPath
    }
    return source.copy(
        enabled = enabled,
        name = name.trim().ifBlank { source.name },
        apiKey = apiKey.trim(),
        baseUrl = resolvedBaseUrl,
        model = source.model,
        timeoutSeconds = timeoutSeconds
            .toIntOrNull()
            ?.coerceIn(5, 600)
            ?: source.timeoutSeconds,
        chatCompletionsPath = savedChatPath,
        responsesApiPath = savedResponsesPath,
        useResponsesApi = useResponsesApi,
        modelsUrl = normalizeAiApiPath(resolvedBaseUrl, modelsUrl.trim()),
        useCustomModelsUrl = useCustomModelsUrl,
        balanceUrl = normalizeAiApiPath(resolvedBaseUrl, balanceUrl.trim()),
        balanceJsonPath = balanceJsonPath.trim(),
        useCustomBalanceUrl = useCustomBalanceUrl,
        streamResponseEnabled = streamResponseEnabled
    )
}
